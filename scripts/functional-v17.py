from playwright.sync_api import sync_playwright
from pathlib import Path
h=Path('/mnt/data/Hanami_Japanese_v17_Standalone.html').read_text()
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-gpu','--disable-web-security'])
 page=b.new_page(viewport={'width':1000,'height':900})
 errs=[];page.on('pageerror',lambda e:errs.append(str(e)))
 page.set_content(h,wait_until='domcontentloaded',timeout=45000)
 page.wait_for_timeout(500)
 print('override speech synth', page.evaluate('''() => {try {Object.defineProperty(window,'speechSynthesis',{configurable:true,value:{cancel(){},getVoices(){return [{lang:'ja-JP',name:'Test Japanese'}]},speak(u){setTimeout(()=>u.onend?.(),12)}}});return true}catch(e){return String(e)}}'''))
 page.locator('[data-page="immersive17"]').click();page.wait_for_timeout(200)
 page.locator('[data-act="v17Open"]').first.click()
 page.locator('[data-act="v17Play"]').click()
 try:
  page.wait_for_function("!document.querySelector('[data-act=v17Answer]')?.disabled",timeout=12000)
  print('episode listening unlock: OK')
  page.locator('[data-act="v17Answer"][data-index="0"]').click()
  page.locator('[data-act="v17Next"]').click()
  page.locator('[data-act="v17Answer"][data-index="1"]').click()
  print('episode end:',page.locator('.v17-finish').inner_text()[:180])
 except Exception as e:print('Episode audio test did not complete:',str(e)[:160])
 page.locator('[data-act="v17Back"]').click()
 page.locator('[data-act="v17Tab"][data-tab="clinics"]').click()
 page.locator('[data-act="v17Clinic"]').first.click()
 page.locator('#v17ClinicAnswer').fill('何してるの？')
 page.locator('[data-act="v17ClinicCheck"]').click()
 print('clinic marked',page.locator('.v17-clinic').first.inner_text()[:45])
 page.locator('[data-act="v17Tab"][data-tab="exam"]').click()
 page.locator('[data-act="v17ExamBegin"][data-id="A"]').click()
 for i,answer in enumerate([1,0,1,1,0]):
  page.locator('[data-act="v17ExamPlay"]').click()
  page.wait_for_function("!document.querySelector('[data-act=v17ExamPick]')?.disabled",timeout=9000)
  page.locator(f'[data-act="v17ExamPick"][data-index="{answer}"]').click()
  page.locator('[data-act="v17ExamNext"]').click()
 print('exam recorded',page.locator('.v17-bank').first.inner_text().replace('\n',' ')[:180])
 print('page errors',errs[:5])
 b.close()
